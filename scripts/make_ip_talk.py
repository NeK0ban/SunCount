"""Презентация к «Экспертной трубе по интеллектуальной собственности» (18.11.2026) — reports/ip_truba/.

Формат задан организаторами: 3 минуты выступления, три слайда — «Проблема, решение и целевая аудитория»,
«Этапы реализации, ресурсы и финансы», «Объекты интеллектуальной собственности» (рекомендации и памятка для команд).
Оформление — шаблон АГУ, как у промежуточного доклада; общие функции — из scripts/make_interim_talk.py.
На слайдах нет схем, кода и формул: публичный показ считается раскрытием (памятка, раздел «Чего не показывать»).

Выход: reports/ip_truba/SunCount_IS_truba.pptx и tekst_vystupleniya.md (текст на 3 минуты, он же в заметках).
Запуск: python scripts/make_ip_talk.py [путь.pptx]
"""
import sys
from pathlib import Path

import pandas as pd
from pptx import Presentation
from pptx.enum.text import MSO_ANCHOR

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from make_interim_talk import (BLUE, L_TITLE, L_TITLE_ONLY, MUTED, TEMPLATE, W0, X0, Y0, add_slide,  # noqa: E402
                               clear_slides, count_tests, drop_empty_placeholders, fill, load_numbers, notes, panel,
                               plural, ru, table, textbox)

OUT_DIR = ROOT / "reports" / "ip_truba"
OUT = OUT_DIR / "SunCount_IS_truba.pptx"
SPEECH_MD = OUT_DIR / "tekst_vystupleniya.md"

# Пошлины (каждое число — с источником; перед подачей заявок сверить с действующей редакцией):
FEE_PROGRAM = 5000    # регистрация программы для ЭВМ: ст. 333.30 НК РФ в ред. закона № 389-ФЗ от 23.11.2024, с 01.01.2025
FEE_DATABASE = 5000   # регистрация базы данных — та же статья и тот же размер (buh.ru, 25.11.2024)
FEE_TRADEMARK = 33000  # товарный знак, один класс МКТУ, электронная подача: 3 500 + 13 500 + 16 000 ₽,
#                        Положение о пошлинах (ПП РФ № 941) по обзору vitvet.com от 22.05.2026
N_INSTALLERS, N_SHOPS, N_CONTACT = 14, 18, 4   # docs/grant/customers.md
KP_3KW = "194–209"    # КП Экопроект-Энерго на станцию около 3 кВт с монтажом и подключением, тыс. ₽ (docs/method/configurator.md)


def numbers() -> dict:
    d = load_numbers()
    ex = d["ex"]
    # смета сервиса для станции около 3 кВт (5 панелей и инвертор 3 кВт) — та, что сверялась с КП установщика
    smeta_3kw = float(ex[(ex.n_panels == 5)].capex_rub.median())
    d.update(smeta_3kw=smeta_3kw, n_tests=count_tests(),
             fees=FEE_PROGRAM + FEE_DATABASE + FEE_TRADEMARK)
    return d


def speech(d: dict) -> list:
    a, b = ru(d["capex"][0] / 1000), ru(d["capex"][1] / 1000)
    nt = d["n_tests"]
    return [
        ("Титул", "Прищепа Максим (Р1)",
         "Добрый вечер. Мы — команда 2 Адыгейского государственного университета, проект SunCount: сервис, который "
         "подбирает домашнюю солнечную электростанцию."),
        ("Проблема, решение и целевая аудитория", "Прищепа Максим (Р1)",
         "Владелец частного дома в Адыгее и Краснодарском крае не может до покупки понять, какая солнечная станция "
         f"ему нужна и когда она окупится. Ошибка стоит от {a} до {b} тысяч рублей. Мы делаем веб-сервис: человек "
         "описывает дом, тариф и крышу и получает готовую станцию — модели оборудования, смету под ключ и срок "
         f"окупаемости. Смета сходится с предложением установщика: {ru(d['smeta_3kw'] / 1000)} тысяч рублей у нас "
         f"против {KP_3KW} тысяч. Пользуется сервисом владелец дома, для него он бесплатный. Платят установщики и "
         f"магазины оборудования, которым нужен честный расчёт для клиента: в нашем списке их "
         f"{N_INSTALLERS + N_SHOPS}, с четырьмя мы уже на связи."),
        ("Этапы реализации, ресурсы и финансы", "Рогочий Александр (Р5)",
         "Исследование и прототип сделаны силами команды, без бюджета. Рабочая версия сервиса будет опубликована "
         f"16 декабря: уже работают каталог оборудования, смета и {nt} {plural(nt, 'автотест', 'автотеста', 'автотестов')}. "
         "В первом квартале 2027 года планируем пилот с двумя установщиками на 3–10 реальных домах. До пилота "
         "оформляем права: соглашение авторов, регистрация программы и базы данных, заявка на товарный знак — около "
         f"{ru(d['fees'] / 1000)} тысяч рублей пошлин. Пилот и оформление прав требуют финансирования, рассчитываем "
         "на грант. Затем — первые лицензии установщикам."),
        ("Объекты интеллектуальной собственности", "Прищепа Максим (Р1)",
         "Наш ключевой объект интеллектуальной собственности — программа для ЭВМ: именно в ней соединены правила "
         "рынка, каталог оборудования и расчёт по часам, чего нет у аналогов. Охраняем её авторским правом и "
         "регистрируем в Роспатенте. Второй объект — база данных: каталог с паспортами и ценами, тарифы и цены "
         "выкупа. Третий — название, товарный знак. Патент не заявляем: методика подбора — математический метод, по "
         "закону это не изобретение, и патентов на такую методику мы не нашли. Авторы — пять участников команды, "
         "письменное соглашение о правах подпишем до пилота. Заказчик получает неисключительную лицензию, права "
         "остаются у авторов. Вопросы к экспертам: кто должен быть заявителем — авторы или вуз, и можно ли "
         "коммерчески использовать цены с сайтов магазинов."),
    ]


def build() -> None:
    d = numbers()
    sp = speech(d)
    prs = Presentation(str(TEMPLATE))
    clear_slides(prs)

    # Титул
    s = add_slide(prs, L_TITLE)
    fill(s.shapes.title.text_frame,
         [{"runs": [("SunCount: система поддержки принятия решений по выбору домашней солнечной электростанции",
                     False)], "size": 36, "color": BLUE, "after": 0}])
    fill(s.placeholders[1].text_frame, [
        {"runs": [("Экспертная труба по интеллектуальной собственности · 18 ноября 2026 г.", True)], "size": 16},
        {"runs": [("Команда 2: ", True), ("Власов Кирилл, Прищепа Максим, Цирульник Юрий, Кривоносов Вячеслав, "
                                          "Рогочий Александр", False)], "size": 16},
        {"runs": [("Наставник: ", True), ("Онищенко Стефан Владимирович", False)], "size": 16},
        {"runs": [("Адыгейский государственный университет, Майкоп", False)], "size": 16},
    ], size=16)
    notes(s, sp[0][1], sp[0][2])

    # Слайд 1. Проблема, решение и целевая аудитория
    s = add_slide(prs, L_TITLE_ONLY, sp[1][0])
    a, b = ru(d["capex"][0] / 1000), ru(d["capex"][1] / 1000)
    textbox(s, X0, Y0 + 0.02, 6.75, 2.9, [
        {"runs": [("Проблема. ", True),
                  ("Владелец частного дома в Адыгее и Краснодарском крае не может до покупки понять, какая солнечная "
                   f"станция ему нужна и когда она окупится. Ошибка стоит {a}–{b} тыс. ₽: переплата за лишнюю мощность "
                   "или отказ от выгодной покупки.", False)], "after": 10},
        {"runs": [("Решение. ", True),
                  ("Веб-сервис подбирает станцию под конкретный дом: человек получает состав оборудования, смету "
                   "«под ключ» и срок окупаемости при своём тарифе — до того, как пойдёт к продавцу.", False)],
         "after": 0},
    ], size=16, name="Проблема и решение")
    x = X0 + 7.0
    w = W0 - 7.0
    panel(s, x, Y0 + 0.08, w, 2.75, "Метрика фон")
    textbox(s, x + 0.2, Y0 + 0.15, w - 0.4, 0.45, [{"runs": [("Ключевая метрика ценности", True)], "size": 14,
                                                    "after": 0}], name="Метрика заголовок")
    textbox(s, x + 0.2, Y0 + 0.6, w - 0.4, 0.75, [{"runs": [(f"{ru(d['smeta_3kw'] / 1000)} тыс. ₽", True)],
                                                   "size": 34, "color": BLUE, "after": 0}], name="Метрика число")
    textbox(s, x + 0.2, Y0 + 1.4, w - 0.4, 1.35, [{"runs": [
        (f"смета сервиса для станции около 3 кВт. Предложение установщика на такую же — {KP_3KW} тыс. ₽", False)],
        "size": 14, "after": 0}], name="Метрика подпись")
    cw = (W0 - 0.3) / 2
    cards = [
        ("Первичная аудитория — пользователь",
         "Владелец частного дома: пользуется сервисом и сам решает, покупать ли станцию. Для него сервис бесплатный. "
         "В крае 1,16 млн частных домов, станция с продажей излишков — меньше чем у 0,1 %."),
        ("Вторичная аудитория — плательщик",
         f"Установщики и магазины оборудования: решают о покупке сервиса и платят за расчёт для своих клиентов. "
         f"В нашем списке {N_INSTALLERS} установщиков и {N_SHOPS} магазинов, с {N_CONTACT} уже на связи."),
    ]
    for k, (head, body) in enumerate(cards):
        cx = X0 + k * (cw + 0.3)
        panel(s, cx, 5.02, cw, 1.6, f"Аудитория {k + 1} фон")
        textbox(s, cx + 0.2, 5.07, cw - 0.4, 0.4, [{"runs": [(head, True)], "size": 15, "color": BLUE, "after": 0}],
                name=f"Аудитория {k + 1} заголовок")
        textbox(s, cx + 0.2, 5.46, cw - 0.4, 1.14, [{"runs": [(body, False)], "size": 14, "after": 0}],
                name=f"Аудитория {k + 1} текст")
    notes(s, sp[1][1], sp[1][2])

    # Слайд 2. Этапы реализации, ресурсы и финансы
    s = add_slide(prs, L_TITLE_ONLY, sp[2][0])
    nt = d["n_tests"]
    rows = [
        ["Этап", "Результат", "Ресурсы", "Бюджет и источники"],
        ["1. Исследование и прототип — сделано",
         "Правила, тарифы, 9 аналогов, модель окупаемости, прототип",
         "Команда из 5 человек, наставник", "0 ₽ — учебный проект"],
        ["2. MVP — до 21.12.2026",
         f"Веб-сервис: каталог, смета, {nt} {plural(nt, 'автотест', 'автотеста', 'автотестов')}; публикация 16.12",
         "Команда; профили от команды 1", "0 ₽ — покрыто"],
        ["3. Пилот — I кв. 2027, план",
         "2 установщика, 3–10 домов; сверка сметы и выработки",
         "Установщики, поддержка сервиса", "Нужен грант, сумма не определена"],
        ["4. Оформление ИС — до пилота",
         "Соглашение авторов; программа, база данных, товарный знак",
         "Юрист по ИС, согласование с вузом",
         f"≈ {ru(d['fees'] / 1000)} тыс. ₽ пошлин — нужны средства"],
        ["5. Продажи — после пилота",
         "Первые лицензии установщикам и магазинам",
         "Продажи, обновление цен", "Выручка, грант"],
    ]
    table(s, X0, Y0 + 0.04, W0, rows, [2.5, 3.4, 2.45, 2.15], size=14, row_h=0.66, name="Таблица этапов")
    textbox(s, X0, 6.3, W0, 0.38, [{"runs": [
        (f"Пошлины: программа и база данных — по {ru(FEE_PROGRAM)} ₽ (ст. 333.30 НК РФ), товарный знак — от "
         f"{ru(FEE_TRADEMARK)} ₽ за один класс (Положение о пошлинах № 941)", False)],
        "size": 12, "color": MUTED, "after": 0}], name="Источник пошлин")
    notes(s, sp[2][1], sp[2][2])

    # Слайд 3. Объекты интеллектуальной собственности
    s = add_slide(prs, L_TITLE_ONLY, sp[3][0])
    rows = [
        ["Объект", "Охрана", "Что защищает", "Вопрос экспертам"],
        ["Программа для ЭВМ SunCount: подбор станции, расчёт окупаемости, веб-интерфейс",
         "Авторское право; регистрация в Роспатенте", "Код программы",
         "Кто заявитель: пять авторов или вуз? Как оформить модуль команды 1?"],
        ["База данных: каталог оборудования с паспортами и ценами, тарифы, цены выкупа",
         "Право на базу данных; регистрация в Роспатенте", "Состав и организацию данных",
         "Можно ли коммерчески использовать цены с сайтов магазинов?"],
        ["Название SunCount", "Товарный знак, классы МКТУ 9 и 42", "Название и узнаваемость",
         "Свободно ли название и какие классы нужны?"],
    ]
    table(s, X0, Y0 + 0.04, W0, rows, [3.25, 2.45, 1.75, 3.05], size=14, row_h=0.72, name="Таблица объектов ИС")
    textbox(s, X0, 5.2, W0, 1.45, [
        {"runs": [("Патент не заявляем: ", True),
                  ("методика подбора — математический метод и программа как таковая (ст. 1350 ГК РФ); патентов на "
                   "такую методику для домашних станций поиск не нашёл.", False)], "after": 5},
        {"runs": [("Права: ", True),
                  ("авторы — пять участников команды; письменное соглашение о правах подпишем до пилота.", False)],
         "after": 5},
        {"runs": [("Заказчику — неисключительная лицензия, ", True),
                  ("права остаются у авторов. Повторить мешают авторское право на код и актуальная база данных.",
                   False)], "after": 0},
    ], size=14, name="Права и ценность", anchor=MSO_ANCHOR.TOP)
    notes(s, sp[3][1], sp[3][2])

    for sl in prs.slides:
        drop_empty_placeholders(sl)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    prs.save(str(OUT))

    words = [len(x[2].split()) for x in sp]
    lines = ["# Текст выступления — Экспертная труба по интеллектуальной собственности", "",
             "18 ноября 2026 г., онлайн, с 18:00 МСК. На выступление — 3 минуты, затем 5 минут вопросов и 5 минут "
             "обратной связи. Презентация — `reports/ip_truba/SunCount_IS_truba.pptx`, тот же текст стоит в заметках "
             "к слайдам. Собирается скриптом `scripts/make_ip_talk.py`: править текст нужно в функции `speech()`.", "",
             f"Всего {sum(words)} слов — около {ru(sum(words) / 130, 1)} минуты при темпе 130 слов в минуту. Больше "
             "390 слов в три минуты не помещается.", ""]
    for n, (title, who, text) in enumerate(sp):
        head = "Титул" if n == 0 else f"Слайд {n}. {title}"
        lines += [f"## {head}", "", f"**Говорит:** {who}, около {round(len(text.split()) / 130 * 60 / 5) * 5} секунд.",
                  "", text, ""]
    SPEECH_MD.write_text("\n".join(lines), encoding="utf-8")
    print(OUT, len(prs.slides), "слайда;", sum(words), "слов")


if __name__ == "__main__":
    if len(sys.argv) > 1:
        OUT = Path(sys.argv[1])
    build()
