INF = float("inf")
NB = " "   # неразрывный пробел: число не отрывается от единицы и не рвётся между разрядами


def _bad(value) -> bool:
    return value is None or (isinstance(value, float) and math.isnan(value))


def format_rub(value: float) -> str:
    """Рубли с пробелами между разрядами: 51903.12 -> '51 903 ₽' (пробелы неразрывные)."""
    if _bad(value):
        return "—"
    if value == INF:
        return "∞"
    return f"{value:,.0f}".replace(",", NB) + NB + "₽"


def format_years(value: float) -> str:
    """Годы — один знак после запятой: 7.74 -> '7,7 года'; inf -> 'не окупается за 25 лет'.

    С дробной частью (а она всегда показывается: «8,0») по-русски пишется «года».
    """
    if _bad(value):
        return "—"
    if value == INF:
        return f"не окупается за {LIFETIME_YEARS} лет"
    return f"{value:.1f}".replace(".", ",") + NB + "года"


def format_years_range(low: float, high: float) -> str:
    """Диапазон сроков: (7.8, 14.6) -> '7,8–14,6 года'."""
    if _bad(low) or _bad(high):
        return "—"
    if low == INF:
        return format_years(low)
    if high == INF:
        return f"от {format_years(low)} до «не окупается»"
    return f"{low:.1f}–{high:.1f}".replace(".", ",") + NB + "года"


def format_percent(value: float) -> str:
    """Проценты целые, половина — вверх: 40.5 -> '41 %'."""
    if _bad(value):
        return "—"
    if value == INF:
        return "∞"
    return f"{math.floor(value + 0.5):.0f}" + NB + "%"


def format_kwh(value: float) -> str:
    """Киловатт-часы с пробелами между разрядами: 1500 -> '1 500 кВт·ч'."""
    return f"{value:,.0f}".replace(",", NB) + NB + "кВт·ч"


