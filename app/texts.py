def verdict(city_key: str, monthly_kwh: float, tariff_key: str, best_kw: int, results: dict) -> str:
    """Одна фраза с выводом для пользователя.

    Рекомендация — по api.recommend: при сроках, различающихся меньше чем на 0,05 года, берётся меньшая
    мощность. Тогда у более мощной станции срок может быть чуть короче — фраза это оговаривает."""
    best = results[best_kw]
    who = (f"Для дома в {CITIES_IN[city_key]} с потреблением {format_kwh(monthly_kwh)} в месяц "
           f"на тарифе «{TARIFFS[tariff_key]['label']}»")
    if best["simple_payback"] > LIFETIME_YEARS:
        return (f"{who} станция не окупается за срок службы ({LIFETIME_YEARS} лет) "
                f"ни при одной из мощностей 3, 5 и 10 кВт.")
    faster = [kw for kw, r in results.items() if r["simple_payback"] < best["simple_payback"]]
    if faster:
        rival = min(faster, key=lambda kw: results[kw]["simple_payback"])
        return (f"{who} рекомендуем станцию **{best_kw}{NB}кВт**: она окупится примерно за "
                f"**{format_years(best['simple_payback'])}** — почти так же быстро, как {rival}{NB}кВт, "
                f"но стоит дешевле. Остальные варианты — в таблице ниже.")
    return (f"{who} быстрее всего окупится станция **{best_kw}{NB}кВт** — примерно за "
            f"**{format_years(best['simple_payback'])}**. Остальные варианты — в таблице ниже.")


