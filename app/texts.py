def _kw(value: float) -> str:
    return f"{value:.2f}".rstrip("0").rstrip(".").replace(".", ",") + NB + "кВт"


def panels_word(n: int) -> str:
    """1 панель, 2–4 панели, 5–20 панелей, 21 панель…"""
    if n % 10 == 1 and n % 100 != 11:
        return "панель"
    if n % 10 in (2, 3, 4) and n % 100 not in (12, 13, 14):
        return "панели"
    return "панелей"


def verdict(best: dict, goal: str) -> str:
    """Одна-две фразы с рекомендацией."""
    head = (
        f"Рекомендуем **{best['n_panels']}{NB}{panels_word(best['n_panels'])} {best['panel']}** "
        f"({_kw(best['kwp'])}) и инвертор **{best['inverter']}**. "
        f"Всё вместе с монтажом и подключением — **{format_rub(best['capex_rub'])}**"
    )
    if best["simple_payback"] > LIFETIME_YEARS:
        return head + f"; при таком потреблении станция не окупается за срок службы ({LIFETIME_YEARS} лет)."
    tail = (
        f", окупится примерно за **{format_years(best['simple_payback'])}**."
        if goal != "npv"
        else f", за 25 лет даст чистую выгоду около **{format_rub(best['npv_rub'])}** "
             f"(окупится за {format_years(best['simple_payback'])})."
    )
    return head + tail


def strings_text(best: dict) -> str:
    s = best["strings"]
    if len(s) == 1:
        return f"одна цепочка из {s[0]} панелей"
    return f"{len(s)} цепочки по {' и '.join(str(x) for x in s)} панелей — каждая на свой вход инвертора"


